//! MIG-02. Given a Docusaurus project whose config and sidebars are literal
//! objects, with MDX, admonitions, versions, i18n, and the client-redirects
//! plugin; when it is imported; then the config and navigation are produced,
//! the four components MIG-02 names are mapped, versions and locales carry,
//! redirects carry, and a config that is not a literal object asks for the Node
//! script instead of guessing.

use liyasa_config::vfs::MemVfs;
use liyasa_core::vfs::VfsPath;
use liyasa_import::docusaurus;

use crate::support::{Builtins, config, pages_scan, paths, text_at, validate};

const CONFIG: &str = r#"
const lightCodeTheme = { plain: {} };

const config = {
  title: 'Acme',
  tagline: 'Docs that work',
  favicon: 'img/favicon.ico',
  url: 'https://acme.example',
  baseUrl: '/',
  organizationName: 'acme',
  projectName: 'docs',
  onBrokenLinks: 'throw',
  i18n: { defaultLocale: 'en', locales: ['en', 'de'] },
  presets: [
    ['classic', {
      docs: { sidebarPath: './sidebars.js', routeBasePath: 'docs' },
      theme: { customCss: './src/css/custom.css' },
    }],
  ],
  plugins: [
    ['@docusaurus/plugin-client-redirects', {
      redirects: [{ to: '/docs/intro', from: ['/welcome', '/start'] }],
    }],
  ],
  themeConfig: {
    navbar: {
      title: 'Acme',
      logo: { alt: 'Acme', src: 'img/logo.svg', srcDark: 'img/logo-dark.svg' },
      items: [
        { type: 'docSidebar', sidebarId: 'tutorialSidebar', position: 'left', label: 'Tutorial' },
        { href: 'https://github.com/acme/docs', label: 'GitHub', position: 'right' },
      ],
    },
    footer: {
      style: 'dark',
      links: [{ title: 'Docs', items: [{ label: 'Tutorial', to: '/docs/intro' }] }],
      copyright: 'Copyright Acme.',
    },
    colorMode: { defaultMode: 'dark', disableSwitch: false },
    prism: { theme: lightCodeTheme },
  },
};

export default config;
"#;

const SIDEBARS: &str = r#"
module.exports = {
  tutorialSidebar: [
    'intro',
    {
      type: 'category',
      label: 'Guides',
      collapsed: false,
      link: { type: 'doc', id: 'guides/index' },
      items: ['guides/install', { type: 'doc', id: 'guides/deploy' }],
    },
    { type: 'link', label: 'Changelog', href: 'https://acme.example/changelog' },
    { type: 'autogenerated', dirName: 'reference' },
  ],
};
"#;

const INTRO: &str = "---\ntitle: Intro\nsidebar_label: Getting started\nsidebar_position: 1\n---\n\nimport Tabs from '@theme/Tabs';\nimport TabItem from '@theme/TabItem';\n\n# Intro\n\n:::tip Pro tip\nRun it twice.\n:::\n\n:::caution\nMind the gap.\n:::\n\n<Tabs groupId=\"pm\">\n  <TabItem value=\"npm\" label=\"npm\" default>\n    npm i acme\n  </TabItem>\n  <TabItem value=\"pnpm\" label=\"pnpm\">\n    pnpm add acme\n  </TabItem>\n</Tabs>\n";

const INSTALL: &str = "---\ntitle: Install\n---\n\nimport CodeBlock from '@theme/CodeBlock';\n\n<CodeBlock language=\"bash\" title=\"install.sh\">\nnpm i acme\n</CodeBlock>\n\n<Admonition type=\"danger\" title=\"Careful\">\nThis deletes things.\n</Admonition>\n";

fn project() -> MemVfs {
    MemVfs::new()
        .with("docusaurus.config.js", CONFIG.as_bytes().to_vec())
        .with("sidebars.js", SIDEBARS.as_bytes().to_vec())
        .with("docs/intro.md", INTRO.as_bytes().to_vec())
        .with("docs/guides/install.mdx", INSTALL.as_bytes().to_vec())
        .with(
            "docs/guides/index.md",
            "---\ntitle: Guides\n---\n\nGuides.\n".as_bytes().to_vec(),
        )
        .with(
            "docs/guides/deploy.md",
            "---\ntitle: Deploy\n---\n\nDeploy.\n".as_bytes().to_vec(),
        )
        .with(
            "docs/reference/api.md",
            "---\ntitle: API\n---\n\nAPI.\n".as_bytes().to_vec(),
        )
        .with("static/img/logo.svg", b"<svg/>".to_vec())
        .with("static/img/favicon.ico", b"icon".to_vec())
        .with("src/css/custom.css", b":root{}".to_vec())
        .with("src/pages/index.js", b"export default () => null".to_vec())
        .with(
            "versioned_docs/version-1.0/intro.md",
            "---\ntitle: Intro\n---\n\nOld.\n".as_bytes().to_vec(),
        )
        .with("versions.json", b"[\"1.0\"]".to_vec())
        .with(
            "i18n/de/docusaurus-plugin-content-docs/current/intro.md",
            "---\ntitle: Einleitung\n---\n\nHallo.\n"
                .as_bytes()
                .to_vec(),
        )
        .with("package.json", b"{}".to_vec())
}

fn import(vfs: &MemVfs) -> liyasa_import::Plan {
    docusaurus::import(
        vfs,
        &VfsPath::new(""),
        &docusaurus::Options {
            components: &Builtins::default(),
            directives: false,
        },
    )
}

#[test]
fn a_literal_config_is_read_in_process() {
    let plan = import(&project());
    assert!(
        plan.report.diagnostics.is_empty(),
        "{:?}",
        plan.report
            .diagnostics
            .iter()
            .map(|d| format!("{}: {}", d.code, d.message))
            .collect::<Vec<_>>()
    );
    let config = config(&plan);
    assert_eq!(config["name"], "Acme");
    assert_eq!(config["description"], "Docs that work");
    assert_eq!(config["seo"]["canonicalOrigin"], "https://acme.example");
    assert_eq!(config["favicon"]["light"], "/img/favicon.ico");
    assert_eq!(config["logo"]["light"], "/img/logo.svg");
    assert_eq!(config["logo"]["dark"], "/img/logo-dark.svg");
    assert_eq!(config["theme"]["appearance"]["default"], "dark");
    assert_eq!(config["theme"]["css"], "/src/css/custom.css");
    assert_eq!(config["navbar"]["links"][0]["label"], "GitHub");
    assert_eq!(config["footer"]["links"][0]["header"], "Docs");
    assert_eq!(config["footer"]["text"], "Copyright Acme.");
}

