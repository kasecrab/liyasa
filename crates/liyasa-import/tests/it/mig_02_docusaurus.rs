#[test]
fn a_config_that_is_not_a_literal_object_asks_for_the_node_script() {
    let vfs = MemVfs::new()
        .with(
            "docusaurus.config.js",
            b"const { themes } = require('prism-react-renderer');\n\
              module.exports = { title: 'Acme', theme: themes.github };\n"
                .to_vec(),
        )
        .with("docs/intro.md", b"# Intro\n".to_vec());
    let plan = import(&vfs);

    assert_eq!(
        plan.report
            .diagnostics
            .iter()
            .map(|d| d.code.as_str())
            .collect::<Vec<_>>(),
        ["E1105"]
    );
    let script = text_at(&plan, "liyasa-export-config.mjs");
    assert_eq!(script.lines().count(), 1, "{script}");
    assert!(
        plan.report
            .diagnostics
            .iter()
            .any(|d| d.help.as_deref().is_some_and(|h| h.contains("node "))),
        "the diagnostic does not say how to run the script"
    );
}

#[test]
fn a_config_exported_as_json_by_that_script_is_read_on_the_next_run() {
    let vfs = MemVfs::new()
        .with(
            "docusaurus.config.js",
            b"module.exports = { title: 'ignored', theme: broken.value };".to_vec(),
        )
        .with(
            "docusaurus.config.json",
            br#"{ "title": "Acme", "presets": [["classic", { "docs": { "routeBasePath": "/" } }]] }"#
                .to_vec(),
        )
        .with("docs/intro.md", b"---\ntitle: Intro\n---\n\nHi.\n".to_vec());
    let plan = import(&vfs);

    assert!(plan.report.diagnostics.is_empty());
    assert_eq!(config(&plan)["name"], "Acme");
    assert!(
        paths(&plan).contains(&"intro.md"),
        "routeBasePath `/` should put the page at the root: {:?}",
        paths(&plan)
    );
}

