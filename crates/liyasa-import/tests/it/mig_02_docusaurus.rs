#[test]
fn admonitions_gain_the_title_prop_and_caution_becomes_warning() {
    let plan = import(&project());
    let intro = text_at(&plan, "docs/intro.md");
    assert!(intro.contains(":::tip{title=\"Pro tip\"}"), "{intro}");
    assert!(intro.contains(":::warning\n"), "{intro}");
    assert!(!intro.contains(":::caution"));
}

#[test]
fn tabs_and_tab_items_are_mapped_at_both_ends() {
    let plan = import(&project());
    let intro = text_at(&plan, "docs/intro.md");
    assert!(intro.contains("<Tabs>"), "{intro}");
    assert!(
        !intro.contains("groupId"),
        "a Docusaurus-only prop survived"
    );
    assert!(
        intro.contains("<Tab title=\"npm\" default=true>"),
        "{intro}"
    );
    assert!(intro.contains("</Tab>"), "{intro}");
    assert!(!intro.contains("TabItem"), "{intro}");
}

