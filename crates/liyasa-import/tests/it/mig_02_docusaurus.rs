#[test]
fn pages_land_where_their_docusaurus_url_says() {
    let plan = import(&project());
    let paths = paths(&plan);
    assert!(paths.contains(&"docs/intro.md"), "{paths:?}");
    assert!(paths.contains(&"docs/guides/install.md"));
    assert!(paths.contains(&"versions/1.0/docs/intro.md"), "{paths:?}");
    assert!(paths.contains(&"locales/de/docs/intro.md"), "{paths:?}");
    for page in &plan.report.pages {
        if page.from.as_str().starts_with("versioned_docs/") {
            continue;
        }
        assert!(
            !page.moved(),
            "{} moved from {} to {}",
            page.from,
            page.old_route,
            page.route
        );
    }
}

#[test]
fn an_archived_version_changes_route_and_gets_a_redirect() {
    let plan = import(&project());
    let archived = plan
        .report
        .pages
        .iter()
        .find(|page| page.from.as_str() == "versioned_docs/version-1.0/intro.md")
        .expect("the archived page is in the report");
    assert_eq!(archived.old_route, "/docs/1.0/intro");
    assert_eq!(archived.route, "/1.0/docs/intro");
    assert!(archived.moved());
    assert!(
        plan.report
            .redirects
            .iter()
            .any(|rule| rule.source == "/docs/1.0/intro"),
        "MIG-05 generates a redirect when the structure changes: {:?}",
        plan.report.redirects
    );
}

