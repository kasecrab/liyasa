//! SHA-256 and Base64 for CSP hash sources (RX-110).
//!
//! CSP accepts `sha256`, `sha384`, and `sha512` and nothing else; the workspace
//! hashes with blake3 and its dependency table (§6.2) carries no SHA-2 crate.
//! The one digest the policy needs is written out here and held to the FIPS
//! 180-4 vectors in the tests, which is a smaller risk than a hash source
//! nobody can verify.

